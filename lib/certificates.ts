import { readdirSync } from "node:fs";
import { join } from "node:path";
import type { CertificateFile } from "@/components/portfolio/certificate-gallery";

const supportedTypes = new Set([".pdf", ".png", ".jpg", ".jpeg", ".webp", ".avif", ".svg"]);

function displayTitle(fileName: string) {
  const withoutExtension = fileName.replace(/\.[^.]+$/, "");
  const readable = withoutExtension.replace(/[_-]+/g, " ").replace(/\s+/g, " ").trim();

  const knownTitles: Record<string, string> = {
    "1st year 1st sem apprecation": "First Year · Semester 1 Appreciation",
    "ACE Scanner_2025_10_29 (1)": "Introduction to Differential Equations",
    "ACE Scanner_20261031(3)": "Digital Electronics",
    "Data_Science_Essentials_with_Python_certificate_2505a41119-sru-edu-in_fdf7c940-815c-45d9-9f53-ab58af2fcda6 (1)": "Data Science Essentials with Python",
    "linear certificate": "Complete Linear Algebra: Theory and Implementation in Code",
    "priya-1": "Smart India Internal Hackathon 2026",
    "spd": "Creativity & Ideation in Entrepreneurship",
    "spd 2": "Innovation & Sustainability",
    "spd 3": "Innovation & Entrepreneurship Launch",
    "spd 4": "Entrepreneurial Leadership",
    "UC-863a6abf-04ac-40ac-8b2b-f9efa2ead86a": "Master Linear Algebra: Theory and Implementation in Code",
  };
  if (knownTitles[withoutExtension]) return knownTitles[withoutExtension];

  return readable.charAt(0).toUpperCase() + readable.slice(1);
}

