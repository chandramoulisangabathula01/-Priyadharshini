export function getCertificateFiles(): CertificateFile[] {
  const directory = join(process.cwd(), "public", "certificates");
  const previewDirectory = join(process.cwd(), "public", "certificate-previews");
  const files = readdirSync(directory, { withFileTypes: true });
  let previews: string[] = [];
  try {
    previews = readdirSync(previewDirectory);
  } catch {
    // Preview assets are generated by the predev and prebuild scripts.
  }

  return files
    .filter((entry) => {
      const extension = entry.name.slice(entry.name.lastIndexOf(".")).toLowerCase();
      return entry.isFile() && supportedTypes.has(extension);
    })
    .map((entry) => {
      const extension = entry.name.slice(entry.name.lastIndexOf(".")).toLowerCase();
      const kind = extension === ".pdf" ? "pdf" : "image";
      const hash = createHash("sha256").update(entry.name).digest("hex").slice(0, 16);
      const previewPages = kind === "pdf"
        ? previews
          .filter((fileName) => fileName.startsWith(`${hash}-p`) && fileName.endsWith(".jpg"))
          .sort((a, b) => Number(a.match(/-p(\d+)\.jpg$/)?.[1]) - Number(b.match(/-p(\d+)\.jpg$/)?.[1]))
          .map((fileName) => `/certificate-previews/${fileName}`)
        : undefined;
      return {
        title: displayTitle(entry.name),
        detail: certificateDetail(entry.name, kind),
        src: `/certificates/${encodeURIComponent(entry.name)}`,
        kind,
        previewPages,
      } satisfies CertificateFile;
    })
    .sort((a, b) => a.title.localeCompare(b.title));
}
